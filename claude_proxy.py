#!/usr/bin/env python3
"""
claude_proxy.py - OpenAI-compatible proxy for the Claude Code CLI.

Exposes /v1/chat/completions and /v1/models as a drop-in replacement for the
OpenAI Chat Completions API. All LLM calls go through the Claude Code CLI
subprocess - no Anthropic API is called directly.

Authentication uses the OpenAI wire format: clients pass
`Authorization: Bearer <key>`, where <key> matches the API_KEY env var
(typically loaded from .env, generated by generate_api_key.py).

Session continuity is keyed on the SHA-256 of the system prompt. The
first completion with a given system prompt starts a new Claude session;
the session_id captured from the CLI's result event is cached in memory
(LRU, TTL-bounded), and subsequent requests with the same system prompt
pass --resume <id>. Different system prompts always start fresh sessions.
"""
