async def _stream_text_only(
    conversation: str,
    system_prompt: Optional[str],
    model: str,
    cid: str,
    created: int,
    cache_key: Optional[str],
) -> AsyncIterator[str]:
    yield _sse(_chunk(cid, model, created, {"role": "assistant"}))

    emitted_len = 0
    try:
        async for line in _run_claude(
            conversation, system_prompt, model,
            streaming=True, has_tools=False, cache_key=cache_key,
        ):
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                continue
            if event.get("type") != "assistant":
                continue
            msg = event.get("message", {})
            full_text = "".join(
                b.get("text", "")
                for b in msg.get("content", [])
                if b.get("type") == "text"
            )
            if len(full_text) > emitted_len:
                delta_text = full_text[emitted_len:]
                emitted_len = len(full_text)
                yield _sse(_chunk(cid, model, created, {"content": delta_text}))
    except OpenAIError as err:
        yield _sse({"error": err.to_body()["error"]})
        yield "data: [DONE]\n\n"
        return

    yield _sse(_chunk(cid, model, created, {}, finish_reason="stop"))
    yield "data: [DONE]\n\n"


async def _stream_with_tools(
    conversation: str,
    system_prompt: Optional[str],
    model: str,
    cid: str,
    created: int,
    cache_key: Optional[str],
) -> AsyncIterator[str]:
    """Streaming with tools: buffer everything, then emit.

    Text can contain partial JSON fences that must be parsed atomically;
    streaming them token-by-token leaks raw tool-call JSON to clients.
    """
    yield _sse(_chunk(cid, model, created, {"role": "assistant"}))

    lines: List[str] = []
    try:
        async for line in _run_claude(
            conversation, system_prompt, model,
            streaming=True, has_tools=True, cache_key=cache_key,
        ):
            lines.append(line)
    except OpenAIError as err:
        yield _sse({"error": err.to_body()["error"]})
        yield "data: [DONE]\n\n"
        return

    full_text = _collect_result_text(lines)
    tool_calls, cleaned_text = _extract_tool_calls(full_text)
    finish_reason = "tool_calls" if tool_calls else "stop"

    if LOG_PROMPTS:
        logger.debug(
            "Response id=%s tool_calls=%d text_chars=%d\n%s",
            cid, len(tool_calls), len(cleaned_text), cleaned_text,
        )
    else:
        logger.info(
            "Response id=%s tool_calls=%d text_chars=%d",
            cid, len(tool_calls), len(cleaned_text),
        )

    if cleaned_text:
        yield _sse(_chunk(cid, model, created, {"content": cleaned_text}))

    if tool_calls:
        yield _sse(
            _chunk(
                cid, model, created,
                {"tool_calls": _tool_calls_with_index(tool_calls)},
            )
        )

    yield _sse(_chunk(cid, model, created, {}, finish_reason=finish_reason))
    yield "data: [DONE]\n\n"


