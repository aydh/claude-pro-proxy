async def _run_claude(
    conversation: str,
    system_prompt: Optional[str],
    model: str,
    streaming: bool,
    has_tools: bool,
    cache_key: Optional[str],
) -> AsyncIterator[str]:
    """Invoke the Claude CLI and yield raw stdout lines.

    - streaming=True  -> --output-format stream-json --verbose (NDJSON)
    - streaming=False -> --output-format json (single JSON line)
    - has_tools=True  -> --allowedTools "" so Claude can't run built-in tools
    - cache_key       -> SHA-256(system_prompt); used to --resume prior session
    """
    base_flags = ["--dangerously-skip-permissions"]

    if streaming:
        cmd = [
            CLAUDE_BIN, "--print", "--model", model,
            "--output-format", "stream-json",
            "--verbose",
            "--include-partial-messages",
            *base_flags,
        ]
    else:
        cmd = [
            CLAUDE_BIN, "--print", "--model", model,
            "--output-format", "json",
            *base_flags,
        ]

    if has_tools:
        cmd += ["--allowedTools", ""]

    if system_prompt:
        cmd += ["--system-prompt", system_prompt]

    resume_id = _session_cache.get(cache_key) if cache_key else None
    if resume_id:
        cmd += ["--resume", resume_id]

    logger.info(
        "Claude CLI: model=%s streaming=%s conv_chars=%d resume=%s",
        _sanitize_log(model), streaming, len(conversation), bool(resume_id),
    )

    env = os.environ.copy()
    env["CLAUDE_HOME"] = os.environ.get(
        "CLAUDE_PROXY_HOME", os.path.expanduser("~/.claude-proxy")
    )
    env["CLAUDE_BASH_NO_LOGIN"] = "1"
    env["CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC"] = "1"

    async with _get_cli_semaphore():
        proc = await asyncio.create_subprocess_exec(
            *cmd,
            stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            env=env,
        )

        if proc.stdin is None or proc.stdout is None or proc.stderr is None:
            raise RuntimeError("Failed to open subprocess pipes")

        try:
            proc.stdin.write(conversation.encode("utf-8"))
            await proc.stdin.drain()
        except (BrokenPipeError, ConnectionResetError):
            pass
        finally:
            try:
                proc.stdin.close()
            except Exception:
                pass

        loop = asyncio.get_running_loop()
        deadline = loop.time() + CLI_TIMEOUT_SECONDS
        captured_session_id: Optional[str] = None
        result_text: Optional[str] = None
        result_is_error = False

        async def _terminate() -> None:
            if proc.returncode is None:
                proc.terminate()
                try:
                    await asyncio.wait_for(proc.wait(), timeout=3)
                except asyncio.TimeoutError:
                    proc.kill()

        try:
            while True:
                remaining = deadline - loop.time()
                if remaining <= 0:
                    raise asyncio.TimeoutError()
                try:
                    raw_line = await asyncio.wait_for(
                        proc.stdout.readline(), timeout=remaining
                    )
                except asyncio.TimeoutError:
                    raise
                if not raw_line:
                    break
                line = raw_line.decode("utf-8", errors="replace").strip()
                if not line:
                    continue
                try:
                    event = json.loads(line)
                    if isinstance(event, dict):
                        sid = event.get("session_id")
                        if sid and isinstance(sid, str):
                            captured_session_id = sid
                        if event.get("type") == "result" and "result" in event:
                            result_text = event["result"]
                            result_is_error = bool(event.get("is_error"))
                except json.JSONDecodeError:
                    if LOG_PROMPTS:
                        logger.debug("Non-JSON line from Claude: %s", line[:120])
                yield line

            try:
                stderr_bytes = await asyncio.wait_for(
                    proc.stderr.read(), timeout=5
                )
            except asyncio.TimeoutError:
                stderr_bytes = b""
            stderr_text = stderr_bytes.decode("utf-8", errors="replace").strip()

            await proc.wait()
            if proc.returncode not in (0, None):
                # Surface the CLI's own error text on failure, regardless of
                # LOG_PROMPTS. Claude reports API/auth failures (e.g. a revoked
                # OAuth token) in the result event's `result` field rather than
                # on stderr, so log both to keep failures legible in the journal
                # without turning on full request/response body logging.
                detail = result_text if result_is_error else None
                logger.warning(
                    "Claude exited with code %d%s%s",
                    proc.returncode,
                    f" - {detail[:500]}" if detail else "",
                    f" - stderr: {stderr_text[:500]}" if stderr_text else "",
                )
                if cache_key:
                    _session_cache.invalidate(cache_key)
            else:
                if stderr_text:
                    logger.debug("Claude stderr: %s", stderr_text[:500])
                if cache_key and captured_session_id:
                    _session_cache.put(cache_key, captured_session_id)

        except asyncio.TimeoutError:
            logger.error("Claude CLI timed out after %.0fs", CLI_TIMEOUT_SECONDS)
            if cache_key:
                _session_cache.invalidate(cache_key)
            await _terminate()
            raise OpenAIError(
                f"Claude CLI timed out after {CLI_TIMEOUT_SECONDS:.0f}s",
                status=504,
                error_type="api_error",
            )

        except asyncio.CancelledError:
            logger.info("Client disconnected - terminating Claude subprocess")
            await _terminate()
            raise


