# Match ```json ... ``` fenced blocks, tolerant of missing trailing newline.
_JSON_FENCE_RE = re.compile(r"```json\s*([\s\S]*?)```", re.MULTILINE)


def _extract_tool_calls(text: str) -> Tuple[List[Dict[str, Any]], str]:
    """Parse ```json tool-call fenced blocks into OpenAI tool_calls format."""
    tool_calls: List[Dict[str, Any]] = []
    removed_spans: List[Tuple[int, int]] = []

    for match in _JSON_FENCE_RE.finditer(text):
        body = match.group(1).strip()
        try:
            parsed = json.loads(body)
        except json.JSONDecodeError:
            continue
        if not isinstance(parsed, dict) or "name" not in parsed:
            continue
        if "arguments" not in parsed and "parameters" not in parsed:
            continue

        args = parsed.get("arguments")
        if args is None:
            args = parsed.get("parameters", {})

        tool_calls.append(
            {
                "id": f"call_{uuid.uuid4().hex[:8]}",
                "type": "function",
                "function": {
                    "name": parsed["name"],
                    "arguments": args if isinstance(args, str) else json.dumps(args),
                },
            }
        )
        removed_spans.append((match.start(), match.end()))

    if not removed_spans:
        return [], text

    cleaned = text
    for start, end in reversed(removed_spans):
        cleaned = cleaned[:start] + cleaned[end:]
    return tool_calls, cleaned.strip()


def _collect_result_text(lines: List[str]) -> str:
    for line in reversed(lines):
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            continue
        if event.get("type") == "result" and "result" in event:
            return event["result"]

    for line in reversed(lines):
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            continue
        if event.get("type") == "assistant":
            msg = event.get("message", {})
            parts = [
                b.get("text", "")
                for b in msg.get("content", [])
                if b.get("type") == "text"
            ]
            if parts:
                return "".join(parts)
    return ""


