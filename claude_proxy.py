@app.post("/v1/chat/completions")
async def chat_completions(
    request: ChatRequest,
    authorization: Optional[str] = Header(None),
):
    _require_api_key(authorization)

    model = request.model or DEFAULT_MODEL
    if model not in _CLAUDE_MODEL_SET:
        raise OpenAIError(
            f"Unknown model {model!r}. Allowed: {', '.join(CLAUDE_MODELS)}",
            param="model",
            code="model_not_found",
        )

    # Resolve tool_choice BEFORE build_prompt so that tool_choice="none"
    # suppresses tool spec injection into the system prompt.
    tool_choice = request.tool_choice
    if isinstance(tool_choice, str) and tool_choice == "none":
        has_tools = False
        request.tools = None
    else:
        has_tools = bool(request.tools)

    conversation, system_prompt = build_prompt(request)
    cid = _completion_id()
    created = int(time.time())
    cache_key = _session_key(system_prompt, request.user)

    logger.info(
        "Request id=%s model=%s stream=%s tools=%d",
        cid, _sanitize_log(model), request.stream, len(request.tools or []),
    )

    if request.stream:
        # Note: once StreamingResponse starts, the HTTP 200 header is already
        # sent. Errors that occur during streaming are emitted as SSE payloads
        # rather than HTTP error status codes.
        if has_tools:
            gen = _stream_with_tools(
                conversation, system_prompt, model, cid, created, cache_key
            )
        else:
            gen = _stream_text_only(
                conversation, system_prompt, model, cid, created, cache_key
            )
        return StreamingResponse(gen, media_type="text/event-stream")

    lines: List[str] = []
    async for line in _run_claude(
        conversation, system_prompt, model,
        streaming=False, has_tools=has_tools, cache_key=cache_key,
    ):
        lines.append(line)

    full_text = _collect_result_text(lines)
    tool_calls, cleaned_text = _extract_tool_calls(full_text)

    if LOG_PROMPTS:
        logger.debug(
            "Response id=%s tool_calls=%d text_chars=%d\n%s",
            cid, len(tool_calls), len(cleaned_text), cleaned_text,
        )
    else:
        logger.info(
            "Response id=%s tool_calls=%d text_chars=%d",
            cid, len(tool_calls), len(cleaned_text),
        )

    return JSONResponse(
        _non_streaming_response(cid, model, created, cleaned_text, tool_calls)
    )


