_TOOL_BLOCK_TEMPLATE = """\
You are operating as a pure language model via an API. You do NOT have access \
to any built-in tools, filesystem, bash, or code execution. The ONLY way to \
invoke an external capability is to emit a fenced JSON code block as described \
below. Do not attempt to execute anything yourself.

When you want to call one of the available tools, emit EXACTLY this format and \
nothing else - no prose before or after:

```json
{{
  "name": "<tool_name>",
  "arguments": {{
    "<arg>": "<value>"
  }}
}}
```

Rules:
- The key MUST be "arguments" (not "parameters" or any other key).
- Emit ONLY the fenced JSON block - no surrounding text before or after.
- You may emit multiple fenced blocks in sequence to call multiple tools.
- Stop immediately after emitting tool call block(s). Do not narrate or explain.
- If no tool is needed, respond in plain text as normal.
- NEVER say a tool is unavailable or failed - just emit the block and stop.

Available tools:
{tool_specs}
"""


def _content_to_text(content: Any) -> str:
    """Normalise OpenAI message content (str or list of text blocks).

    Raises OpenAIError on unsupported content types (images, audio, etc.).
    """
    if content is None:
        return ""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts: List[str] = []
        for block in content:
            if not isinstance(block, dict):
                raise OpenAIError(
                    f"Unsupported content block: expected object, got {type(block).__name__}",
                    param="messages",
                )
            block_type = block.get("type")
            if block_type == "text":
                parts.append(block.get("text", ""))
            else:
                raise OpenAIError(
                    f"Unsupported content block type {block_type!r}. "
                    "Only 'text' blocks are supported by this proxy.",
                    param="messages",
                )
        return "\n".join(parts)
    raise OpenAIError(
        f"Unsupported content type: {type(content).__name__}",
        param="messages",
    )


def _serialize_assistant_tool_calls(tool_calls: List[Dict[str, Any]]) -> str:
    blocks: List[str] = []
    for tc in tool_calls:
        fn = tc.get("function") or {}
        name = fn.get("name") or "unknown"
        raw_args = fn.get("arguments", "{}")
        if isinstance(raw_args, str):
            try:
                args_obj: Any = json.loads(raw_args) if raw_args else {}
            except json.JSONDecodeError:
                args_obj = {"_raw": raw_args}
        else:
            args_obj = raw_args
        payload = json.dumps({"name": name, "arguments": args_obj}, indent=2)
        blocks.append(f"```json\n{payload}\n```")
    return "\n\n".join(blocks)


def build_prompt(request: ChatRequest) -> Tuple[str, Optional[str]]:
    """Convert OpenAI messages into a plain-text conversation prompt.

    Returns (conversation_prompt, system_prompt).
    """
    system_parts: List[str] = []
    conv_lines: List[str] = []

    call_id_to_name: Dict[str, str] = {}
    for msg in request.messages:
        if msg.get("role") == "assistant":
            for tc in msg.get("tool_calls") or []:
                cid = tc.get("id")
                name = ((tc.get("function") or {}).get("name")) if isinstance(tc, dict) else None
                if cid and name:
                    call_id_to_name[cid] = name

    for msg in request.messages:
        role = msg.get("role", "")
        text = _content_to_text(msg.get("content"))

        if role == "system":
            system_parts.append(text)
        elif role == "user":
            conv_lines.append(f"User: {text}")
        elif role == "assistant":
            tcs = msg.get("tool_calls") or []
            serialized = _serialize_assistant_tool_calls(tcs) if tcs else ""
            combined = "\n\n".join(p for p in (text, serialized) if p)
            conv_lines.append(f"Assistant: {combined}")
        elif role == "tool":
            cid = msg.get("tool_call_id") or ""
            name = call_id_to_name.get(cid) or msg.get("name") or cid or "tool"
            conv_lines.append(f"Tool Result [{name}]: {text}")
        else:
            raise OpenAIError(
                f"Unsupported message role: {role!r}",
                param="messages",
            )

    system_prompt: Optional[str] = "\n\n".join(system_parts) if system_parts else None

    if request.tools:
        tool_specs = json.dumps(
            [
                {
                    "name": t.function.name,
                    "description": t.function.description,
                    "parameters": t.function.parameters,
                }
                for t in request.tools
            ],
            indent=2,
        )
        tool_block = _TOOL_BLOCK_TEMPLATE.format(tool_specs=tool_specs)
        system_prompt = (
            (system_prompt + "\n\n" + tool_block) if system_prompt else tool_block
        )

    if system_prompt is not None and len(system_prompt.encode("utf-8")) > MAX_SYSTEM_PROMPT_BYTES:
        raise OpenAIError(
            f"System prompt exceeds {MAX_SYSTEM_PROMPT_BYTES} bytes "
            "(argv limit). Shorten the system messages or tool specs.",
            status=413,
            error_type="invalid_request_error",
            param="messages",
        )

    conversation = "\n\n".join(conv_lines)

    if LOG_PROMPTS:
        logger.debug(
            "system_prompt (%d chars):\n%s",
            len(system_prompt or ""),
            _sanitize_log(system_prompt or ""),
        )
        logger.debug(
            "conversation (%d chars):\n%s",
            len(conversation),
            _sanitize_log(conversation),
        )
    else:
        logger.debug(
            "prompt built: system=%d chars  conversation=%d chars",
            len(system_prompt or ""),
            len(conversation),
        )

    return conversation, system_prompt


